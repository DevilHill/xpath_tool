'use strict';
const {test} = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const net = require('node:net');
const {BridgeManager} = require('../src/bridge');
const {request} = require('../src/core');

test('真实桥接子进程：持久化、导入导出、复用与进程清理', async t => {
  const temp = await fs.mkdtemp(path.join(os.tmpdir(),'wbot-vscode-'));
  const server = net.createServer();
  await new Promise(resolve => server.listen(0,'127.0.0.1',resolve));
  const port = server.address().port;
  await new Promise(resolve => server.close(resolve));
  const cfg = {baseUrl:`http://127.0.0.1:${port}`,libraryPath:path.join(temp,'elements.sqlite3')};
  const manager = new BridgeManager(path.resolve(__dirname,'../runtime'));
  const external = new BridgeManager(path.resolve(__dirname,'../runtime'));
  t.after(async () => { await external.stop(); await manager.stop(); await fs.rm(temp,{recursive:true,force:true}); });
  const started = await manager.start(process.env.WBOT_TEST_PYTHON || 'python',cfg);
  assert.equal(started.owned,true);
  assert.equal(started.health.wbot,'0.1.0');
  const record = {name:'搜索框',group:'首页',xpath:'//input[@id="q"]',url:'https://example.com'};
  const saved = await request(cfg.baseUrl,'/api/elements/save',{record});
  const items = (await request(cfg.baseUrl,'/api/elements')).items;
  assert.equal(items.length,1); assert.equal(items[0].name,record.name);
  const exported = (await request(cfg.baseUrl,'/api/elements/export')).data;
  assert.equal(exported.format,'wbot-elements');
  await request(cfg.baseUrl,'/api/elements/delete',{id:saved.item.id});
  assert.equal((await request(cfg.baseUrl,'/api/elements')).items.length,0);
  await request(cfg.baseUrl,'/api/elements/import',{data:exported,conflict:'error'});
  assert.equal((await request(cfg.baseUrl,'/api/elements')).items.length,1);
  const reused = await external.start('unused-python',cfg);
  assert.equal(reused.owned,false);
  assert.equal(await external.stop(),false);
  assert.equal((await request(cfg.baseUrl,'/api/health')).ok,true);
  assert.equal(await manager.stop(),true);
  await assert.rejects(request(cfg.baseUrl,'/api/health'));
  await manager.start(process.env.WBOT_TEST_PYTHON || 'python',cfg);
  assert.equal((await request(cfg.baseUrl,'/api/elements')).items[0].name,record.name);
});
